// Package db provides database initialization, credential management, and operations.
package db

import (
	"crypto/rand"
	"encoding/base64"
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"sync"
)

var secretMu sync.RWMutex

// GenerateRandomPassword creates a cryptographically secure random password.
func GenerateRandomPassword(length int) (string, error) {
	if length < 16 {
		length = 24
	}
	bytes := make([]byte, length)
	if _, err := rand.Read(bytes); err != nil {
		return "", fmt.Errorf("crypto/rand error: %w", err)
	}
	// Use URL-safe base64 without padding to avoid tricky shell escape issues
	pwd := base64.RawURLEncoding.EncodeToString(bytes)
	if len(pwd) > length {
		pwd = pwd[:length]
	}
	return pwd, nil
}

// GetOrCreateRootPassword retrieves the MariaDB root password or creates a new one in data/.secrets.
func GetOrCreateRootPassword(dataDir string) (string, bool, error) {
	secretMu.Lock()
	defer secretMu.Unlock()

	secretPath := filepath.Join(dataDir, ".secrets")

	if content, err := os.ReadFile(secretPath); err == nil {
		for _, line := range strings.Split(string(content), "\n") {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "MARIADB_ROOT_PASSWORD=") {
				pwd := strings.TrimPrefix(line, "MARIADB_ROOT_PASSWORD=")
				if pwd != "" {
					return pwd, false, nil // false = already existed
				}
			}
		}
	}

	// Generate new random password
	pwd, err := GenerateRandomPassword(24)
	if err != nil {
		return "", false, err
	}

	if err := os.MkdirAll(dataDir, 0700); err != nil {
		return "", false, fmt.Errorf("cannot create data dir: %w", err)
	}

	fileContent := fmt.Sprintf("# Generated by webserver stack — KEEP CONFIDENTIAL\nMARIADB_ROOT_PASSWORD=%s\n", pwd)
	if err := os.WriteFile(secretPath, []byte(fileContent), 0600); err != nil {
		return "", false, fmt.Errorf("cannot save .secrets: %w", err)
	}

	return pwd, true, nil // true = newly generated
}

// ResetRootPassword updates the password in data/.secrets.
func ResetRootPassword(dataDir, newPassword string) error {
	secretMu.Lock()
	defer secretMu.Unlock()

	secretPath := filepath.Join(dataDir, ".secrets")
	fileContent := fmt.Sprintf("# Generated by webserver stack — KEEP CONFIDENTIAL\nMARIADB_ROOT_PASSWORD=%s\n", newPassword)
	return os.WriteFile(secretPath, []byte(fileContent), 0600)
}
