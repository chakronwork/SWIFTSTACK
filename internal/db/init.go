// InitializeDatabase bootstraps the MariaDB data directory and secures root user.
func InitializeDatabase(cfg *config.AppConfig) error {
	log := logger.G()
	dataSQL := cfg.Paths.DataSQL

	// Check if already initialized
	markerFile := filepath.Join(dataSQL, "mysql")
	if _, err := os.Stat(markerFile); err == nil {
		log.Info("MariaDB database already initialized in %s", dataSQL)
		return nil
	}

	log.Info("Initializing MariaDB data directory in %s ...", dataSQL)

	if err := os.MkdirAll(dataSQL, 0755); err != nil {
		return fmt.Errorf("cannot create dataSQL dir: %w", err)
	}

	installDbExe := filepath.Join(cfg.Paths.MariaDBBinDir(), "mariadb-install-db.exe")
	if _, err := os.Stat(installDbExe); err != nil {
		installDbExe = filepath.Join(cfg.Paths.MariaDBBinDir(), "mysql_install_db.exe")
		if _, err := os.Stat(installDbExe); err != nil {
			return fmt.Errorf("mariadb-install-db not found at %s. Ensure MariaDB is extracted", cfg.Paths.MariaDBBinDir())
		}
	}

	// Get or generate random root password
	rootPwd, isNew, err := GetOrCreateRootPassword(cfg.Paths.Data)
	if err != nil {
		return fmt.Errorf("failed generating root password: %w", err)
	}

	if isNew {
		log.Info("Generated secure random password for MariaDB root user")
	}

	// mariadb-install-db argument syntax
	dataDirFwd := templates.ToForwardSlash(dataSQL)
	cmd := exec.Command(installDbExe, fmt.Sprintf("--datadir=%s", dataDirFwd), fmt.Sprintf("--password=%s", rootPwd))
	cmd.Dir = cfg.Paths.MariaDBBinDir()

	output, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("database initialization failed: %w\nOutput: %s", err, string(output))
	}

	log.Info("MariaDB base tables initialized successfully")
	return nil
}

// ChangeRootPassword connects via mariadb-admin to change root password.
func ChangeRootPassword(cfg *config.AppConfig, oldPwd, newPwd string) error {
	adminExe := filepath.Join(cfg.Paths.MariaDBBinDir(), "mariadb-admin.exe")
	if _, err := os.Stat(adminExe); err != nil {
		adminExe = filepath.Join(cfg.Paths.MariaDBBinDir(), "mysqladmin.exe")
	}

	args := []string{"-u", "root"}
	if oldPwd != "" {
		args = append(args, fmt.Sprintf("-p%s", oldPwd))
	}
	args = append(args, "password", newPwd)

	cmd := exec.Command(adminExe, args...)
	cmd.Dir = cfg.Paths.MariaDBBinDir()

	if out, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("failed to change MariaDB password: %w\nOutput: %s", err, string(out))
	}

	return ResetRootPassword(cfg.Paths.Data, newPwd)
}

// EnsureSecureGitignore creates a .gitignore in data/ so credentials and DB files are never committed.
func EnsureSecureGitignore(dataDir string) error {
	gitignore := filepath.Join(dataDir, ".gitignore")
	content := "# Generated by webserver stack\n*\n!.gitignore\n"
	return os.WriteFile(gitignore, []byte(content), 0644)
}

